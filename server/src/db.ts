import { MongoClient, type Db } from "mongodb";
import { DB_NAME, MONGO_URL } from "./config.ts";

export interface ClientDoc {
  _id: string; // client uuid, generated by the browser (localStorage)
  firstSeen: number;
  lastSeen: number;
  userAgent?: string;
}

export interface ModelDoc {
  _id: string;
  game: string;
  group: string; // storage key, e.g. "cave_5" or "circuit_mixed_2"
  clientId: string;
  score?: number;
  model: Record<string, unknown>;
  submittedAt: number;
}

export interface ScoreDoc {
  _id: string;
  game: string;
  seed: string; // normalized; "live" for games without a seed
  group?: string;
  clientId: string;
  score: number;
  modelId?: string;
  verified: boolean;
  submittedAt: number;
  verifiedAt?: number;
  verifiedBy?: string; // client uuid of the verifying process
  replayedScore?: number;
}

export type MongoState = "unconfigured" | "connecting" | "connected" | "error";

let state: MongoState = MONGO_URL ? "connecting" : "unconfigured";
let pending: Promise<Db> | null = null;

export function mongoState(): MongoState {
  return state;
}

export class MongoNotReadyError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "MongoNotReadyError";
  }
}

// Lazy connection: the server boots and serves /healthz even before
// MONGO_URL is configured; API routes return 503 until Mongo is reachable.
export function getDb(): Promise<Db> {
  if (!MONGO_URL) {
    return Promise.reject(
      new MongoNotReadyError("MONGO_URL is not configured on the server"),
    );
  }
  if (!pending) {
    pending = (async () => {
      const client = new MongoClient(MONGO_URL, { serverSelectionTimeoutMS: 5000 });
      await client.connect();
      const db = client.db(DB_NAME);
      // createIndex materializes the collections and sets up the lookups.
      await db.collection<ModelDoc>("models").createIndex({ game: 1, group: 1, submittedAt: -1 });
      await db.collection<ScoreDoc>("scores").createIndex({ game: 1, verified: 1, score: -1 });
      await db.collection<ScoreDoc>("scores").createIndex({ clientId: 1, submittedAt: -1 });
      state = "connected";
      console.log(`mongo connected: ${db.databaseName}`);
      return db;
    })();
    pending.catch((err) => {
      // Reset so the next request retries the connection (e.g. after a
      // MONGO_URL fix or Mongo coming back up).
      state = "error";
      pending = null;
      console.error("mongo connection failed:", err instanceof Error ? err.message : err);
    });
  }
  return pending;
}
